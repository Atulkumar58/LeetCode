class ProductOfNumbers {
public:
    vector<int>st;
    ProductOfNumbers() {
        
    }
    
    void add(int num) {
        st.push_back(num);
    }
    
    int getProduct(int k) {
        int n= st.size();
        int ans=1;
        for(int i=n-1; i>=n-k; i--){
            ans*=st[i];
        }
        return ans;
    }
};

